"""Regenerate the data references agents read directly (no Python needed at run time):
skills/_shared/data/berdo-peers.md, ma-programs.md, emission-factors.md.

Run: python scripts/build_skill_references.py
"""

import hashlib
import json
import sys
from pathlib import Path
from statistics import median, quantiles

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from benji import berdo  # noqa: E402

OUT = ROOT / "skills" / "_shared" / "data"
OUT.mkdir(parents=True, exist_ok=True)
TYPES = ["Office", "Multifamily Housing", "Retail Store", "Supermarket/Grocery Store", "Medical Office",
         "K-12 School", "Hotel", "Worship Facility"]
FOOD = ["Restaurant", "Fast Food Restaurant", "Food Service", "Other - Restaurant/Bar", "Bar/Nightclub"]
BANDS = [(0, 20000), (20000, 50000), (50000, 100000), (100000, 250000), (250000, 10 ** 9)]


def fmt(x):
    return "-" if x is None else f"{x:,.1f}"


def stats(rows, key):
    v = sorted(r[key] for r in rows if r.get(key) is not None)
    if len(v) < 4:
        return None, None, None
    q1, q2, q3 = quantiles(v, n=4)
    return q1, q2, q3


rows = [r for r in berdo.load() if r["site_eui"] and 1 <= r["site_eui"] <= 1000 and r["gfa"]]
for r in rows:
    r["elec_kwh_sf"] = r["elec_kwh"] / r["gfa"] if r["elec_kwh"] else None
    r["gas_kbtu_sf"] = r["gas_kbtu"] / r["gfa"] if r["gas_kbtu"] else None
sha = hashlib.sha256(berdo.RAW.read_bytes()).hexdigest()

L = ["# Boston BERDO peer statistics (generated)", "",
     f"Source: {berdo.SOURCE['title']}. Reporting year {berdo.SOURCE['reporting_year']}. File SHA-256 `{sha}`.",
     "Generated by `scripts/build_skill_references.py`. Do not edit by hand.", "",
     "How these numbers were made:",
     "- Site EUI = Total Site Energy (kBtu) / Gross Floor Area. The workbook's own 'Site EUI' column is about 19x "
     "smaller than its totals imply, so it is NOT used.",
     "- Rows kept: EUI between 1 and 1000 kBtu/sq ft and a floor area present. Peers that use district steam are "
     "excluded in the 'no steam' columns.",
     "- Electricity and gas intensities count only buildings that report that fuel.", "",
     "Rules for using this table (see `../evidence-rules.md`):",
     "- Use it only when the building has 12 months of bills for EVERY fuel it uses and the bills cover the whole building.",
     "- n < 30 means **Insufficient comparable data**: say so, and do not give a percentile.",
     "- BERDO covers large Boston buildings (15+ units or 20,000+ sq ft). Do not use it for 1-4 unit homes.",
     "- A gap to the median says where to look. It is not a saving.", "",
     "| Property type | Floor area band (sq ft) | n (no steam) | Site EUI Q1 | Median | Q3 | Elec kWh/sq ft median | Gas kBtu/sq ft median |",
     "|---|---|---|---|---|---|---|---|"]
groups = [(t, [t]) for t in TYPES] + [("Restaurants / food service (combined)", FOOD)]
for label, types in groups:
    g = [r for r in rows if r["largest_type"] in types and not (r["steam_kbtu"] or 0) > 0]
    for lo, hi in BANDS + [(0, 10 ** 9)]:
        b = [r for r in g if lo <= r["gfa"] < hi]
        if not b:
            continue
        q1, q2, q3 = stats(b, "site_eui")
        e = stats(b, "elec_kwh_sf")[1]
        gs = stats(b, "gas_kbtu_sf")[1]
        band = "all sizes" if (lo, hi) == (0, 10 ** 9) else (f"{lo:,}-{hi:,}" if hi < 10 ** 9 else f"{lo:,}+")
        L.append(f"| {label} | {band} | {len(b)} | {fmt(q1)} | {fmt(q2)} | {fmt(q3)} | {fmt(e)} | {fmt(gs)} |")
(OUT / "berdo-peers.md").write_text("\n".join(L) + "\n", encoding="utf-8")

ef = berdo.emission_factors()
(OUT / "emission-factors.md").write_text(f"""# Emission factors (generated)

| Fuel | Factor | Unit | Basis |
|---|---|---|---|
| Electricity | {ef['electricity_kg_per_kwh']} | kgCO2e per kWh | {ef['accounting']} |
| Natural gas | {ef['natural_gas_kg_per_therm']} | kgCO2e per therm | Same derivation |

Geography: {ef['geography']}. Year: {ef['year']}. Source: {ef['source']}. Sample: {ef['sample_sizes']} buildings.

These are **historical accounting averages**. They are not marginal-grid factors and not a forecast. Always state the
factor, its year and its unit next to any emissions number. Do not add electricity-related emissions and on-site
combustion twice. For fuels not listed here (oil, propane, steam), say that no factor is loaded instead of guessing one.
""", encoding="utf-8")

cat = json.loads((ROOT / "benji" / "catalog" / "incentives.json").read_text(encoding="utf-8"))
P = ["# Massachusetts program leads (generated from benji/catalog/incentives.json)", "",
     f"Catalog version {cat['catalog_version']}. {cat['notice']}", "",
     "Every record is a **lead**. Before relying on one, open the official page, then record the URL, the date checked "
     "and what it says in memory (`decisions.md`). Use the sector column strictly: residential programs never go to "
     "businesses, and the other way round.", "",
     "Mass Save sponsors (electric): " + ", ".join(cat["mass_save_sponsors"]["electric"]) + ". Gas: "
     + ", ".join(cat["mass_save_sponsors"]["gas"]) + ". Municipal-utility customers have separate programs.", ""]
for r in cat["records"]:
    conds = "; ".join(c["description"] for c in r["conditions"]) or "none listed"
    P += [f"## {r['name']}  (`{r['id']}`)", "",
          f"- Sector: {', '.join(r['sectors'])}. Type: {r['incentive_type']}. Paid: {r['timing'].replace('_', ' ')}. "
          f"Pre-approval: {r['preapproval_required']}.",
          f"- Measures: {', '.join(r['measures'])}.",
          f"- Known conditions: {conds}.",
          f"- Amount: {r['amount']['summary']}",
          f"- Cannot be combined with other records in group: {r['stacking_group'] or 'none'}.",
          f"- Source: {r['source_url']} ({r['verification_status']}{', checked ' + r['verified_on'] if r['verified_on'] else ''}).",
          f"- Notes: {r['notes']}", ""]
(OUT / "ma-programs.md").write_text("\n".join(P), encoding="utf-8")
print("wrote", [p.name for p in OUT.iterdir()])
